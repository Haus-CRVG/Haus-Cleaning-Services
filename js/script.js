const ARROWS_SVG = '<svg viewBox="0 0 24 24" fill="none" stroke-width="2" stroke-linecap="round"><path d="M8 5 3 12l5 7M16 5l5 7-5 7"/></svg>';

function buildCompareCard(item) {
    const figure = document.createElement("figure");
    figure.className = "compare-card";

    figure.innerHTML = `
        <div class="compare" data-id="${item.id}">
            <img class="img-before" src="${item.before}" alt="${item.id} before cleaning">
            <img class="img-after" src="${item.after}" alt="${item.id} after cleaning">
            <span class="tag before" data-i18n="tag.before">Before</span>
            <span class="tag after" data-i18n="tag.after">After</span>
            <div class="handle"><div class="handle-grip">${ARROWS_SVG}</div></div>
            <input type="range" min="0" max="100" value="50" aria-label="Reveal before and after">
        </div>
        <figcaption data-caption='${JSON.stringify(item.caption)}'></figcaption>
    `;

    return figure;
}

function initCompareSlider(card) {
    const range = card.querySelector("input[type=range]");
    const setReveal = val => card.style.setProperty("--reveal", val + "%");
    setReveal(range.value);
    range.addEventListener("input", () => setReveal(range.value));
}

function renderGallery(items) {
    const grid = document.getElementById("compareGrid");
    grid.innerHTML = "";

    items.forEach(item => {
        const figure = buildCompareCard(item);
        grid.appendChild(figure);
        initCompareSlider(figure.querySelector(".compare"));
    });

    applyLang(currentLang);
}

fetch("gallery.json")
    .then(res => {
        if (!res.ok) throw new Error("gallery.json not found");
        return res.json();
    })
    .then(data => renderGallery(data))
    .catch(() => renderGallery(FALLBACK_GALLERY));

