const contactForm = document.getElementById("contactForm");
const formSubmitBtn = document.getElementById("formSubmitBtn");
const formSuccess = document.getElementById("formSuccess");
const formError = document.getElementById("formError");

function openEmailModal(e) {
    e.preventDefault();
    emailModal.classList.add("open");
    emailModal.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";

    formSuccess.classList.remove("show");
    formError.classList.remove("show");

    setTimeout(() => {
        document.getElementById("name").focus();
    }, 250);
}

function closeEmailModalFunction() {
    emailModal.classList.remove("open");
    emailModal.setAttribute("aria-hidden", "true");
    document.body.style.overflow = "";
}

emailHeroBtn.addEventListener("click", openEmailModal);
emailCardBtn.addEventListener("click", openEmailModal);
emailListBtn.addEventListener("click", openEmailModal);
closeEmailModal.addEventListener("click", closeEmailModalFunction);

emailModal.addEventListener("click", e => {
    if (e.target === emailModal) {
        closeEmailModalFunction();
    }
});

document.addEventListener("keydown", e => {
    if (e.key === "Escape" && emailModal.classList.contains("open")) {
        closeEmailModalFunction();
    }
});

/* =========================================================
   FORM SUBMISSION - FORMSPREE
========================================================== */

contactForm.addEventListener("submit", async e => {
    e.preventDefault();

    formSuccess.classList.remove("show");
    formError.classList.remove("show");
    formSubmitBtn.disabled = true;

    const buttonText = formSubmitBtn.querySelector("[data-i18n='form.send']");
    if (buttonText) {
        buttonText.textContent = translations[currentLang]["form.sending"];
    }

    const formData = new FormData(contactForm);

    try {
        const response = await fetch(contactForm.action, {
            method: "POST",
            body: formData,
            headers: { "Accept": "application/json" }
        });

        if (response.ok) {
            contactForm.reset();
            formSuccess.classList.add("show");

            if (buttonText) {
                buttonText.textContent = translations[currentLang]["form.send"];
            }
            formSubmitBtn.disabled = false;
        } else {
            throw new Error("Formspree submission failed");
        }
    } catch (error) {
        console.error("Form submission error:", error);
        formError.classList.add("show");

        if (buttonText) {
            buttonText.textContent = translations[currentLang]["form.send"];
        }
        formSubmitBtn.disabled = false;
    }
});

