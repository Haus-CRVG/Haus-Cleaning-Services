const WHATSAPP_NUMBER = "17747079964";
let currentLang = "en";

/* =========================================================
   APPLY LANGUAGE
========================================================== */

function applyLang(lang) {
    currentLang = lang;
    const dict = translations[lang];

    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }
    });

    /* Gallery captions */
    document.querySelectorAll("figcaption[data-caption]").forEach(el => {
        try {
            const caption = JSON.parse(el.getAttribute("data-caption"));
            el.textContent = caption[lang] || caption.en || "";
        } catch (e) {
            /* Ignora legendas inválidas */
        }
    });

    document.documentElement.lang = lang;

    document.querySelectorAll("#langSwitch button").forEach(button => {
        button.classList.toggle("active", button.getAttribute("data-lang") === lang);
    });

    const waLink = `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(dict["wa.msg"])}`;
    ["waHero", "waList", "waCard"].forEach(id => {
        const el = document.getElementById(id);
        if (el) el.href = waLink;
    });
    // Link dentro da notinha do formulário (é recriado a cada troca de idioma, então buscamos de novo)
    const formWaLink = document.getElementById("formWhatsappLink");
    if (formWaLink) formWaLink.href = waLink;
}

/* =========================================================
   LANGUAGE SWITCH
========================================================== */

document.getElementById("langSwitch").addEventListener("click", e => {
    const btn = e.target.closest("button[data-lang]");
    if (!btn) return;
    applyLang(btn.getAttribute("data-lang"));
});

